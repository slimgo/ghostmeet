    /// Сторож класса дефектов, а не отдельной строки.
    ///
    /// Три редакции правила подряд запрещали неправильную форму, печатая её:
    /// «и „бакеты (бакеты)“ — мусор», «не оригинал латиницей („промис
    /// (promise)“)», «не по слогам („мак-ро-таск“)». Замер показал, что запрет
    /// так не работает: пять моделей из пяти, двенадцать испорченных скобок из
    /// двадцати одной, и **четыре из двенадцати — дословные копии этих самых
    /// строк**. Слабый исполнитель читает запрещённый образец как показ формы.
    ///
    /// Поэтому проверяется не наличие правильных слов, а отсутствие самой формы:
    /// в собранном промпте не должно быть ни одной скобки, слева от которой
    /// кириллица, а внутри — одно слово. Именно так выглядят все три вида мусора
    /// («микротаски (микротаски)», «промис (promise)», «слогам («мак-ро-таск»)»),
    /// и именно так **не** выглядит ни одна законная вставка промпта: настоящие
    /// пояснения в скобках многословны («(код, алгоритм, тест, форма)»), а
    /// «собеседник(и)» идёт без пробела.
    @Test("В промпте нет ни одного образца испорченной скобки — их копируют дословно")
    func thePromptShowsNoBrokenBracket() throws {
        let pattern = try Regex(#"[А-Яа-яЁё][А-Яа-яЁё\-]{2,}\s+\([^)\s]+\)"#)

        for (name, system) in [
            ("коротко", BriefPrompt.system(profile: .empty)),
            ("подробно", AssistPrompt.system(profile: .empty)),
        ] {
            let found = system.matches(of: pattern).map { String(system[$0.range]) }
            #expect(found.isEmpty, "жанр «\(name)» показывает испорченную форму: \(found)")
        }
    }


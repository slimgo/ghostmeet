    @Test("Контракт вывода стоит и в начале, и в конце: у длинного промпта работают оба края")
    func theOutputContractBracketsTheRules() {
        let system = BriefPrompt.system(profile: .empty)
        let rulesStart = system.range(of: "Говорит он коротко")!.lowerBound

        // Начало: рамка «это его фраза» — до всякого списка правил …
        #expect(system.range(of: "его собственную следующую фразу")!.lowerBound < rulesStart)
        // … и она же одной строкой после блока родов вопросов.
        let closing = "**Главное, ещё раз: ты пишешь фразу, которую пользователь через секунду скажет вслух своим голосом."
        #expect(system.contains(closing))
        #expect(
            system.range(of: closing)!.lowerBound
                > system.range(of: "**Задача на экране**")!.lowerBound,
            "повтор обязан стоять после правил, иначе конец промпта снова достанется справочным данным"
        )
    }


@Suite("Язык ответа назван в промпте")
struct AnswerLanguageTests {

    /// Замер: без этой строки claude-haiku-4.5 отвечал по-английски **один раз из
    /// пяти** на английском звонке, со строкой — десять из десяти. Причина в том,
    /// что промпт на 96 % кириллический, и он же — сильнейший сигнал о языке.
    @Test("На английском звонке промпт говорит отвечать по-английски")
    func anEnglishCallIsToldSo() {
        let system = BriefPrompt.system(profile: .empty, language: .english)
        #expect(system.contains("ЯЗЫК ОТВЕТА — АНГЛИЙСКИЙ"))
        #expect(system.contains("ЯЗЫК ОТВЕТА — РУССКИЙ") == false)
    }

    @Test("На русском звонке — по-русски")
    func aRussianCallIsToldSo() {
        let system = BriefPrompt.system(profile: .empty, language: .russian)
        #expect(system.contains("ЯЗЫК ОТВЕТА — РУССКИЙ"))
        #expect(system.contains("ЯЗЫК ОТВЕТА — АНГЛИЙСКИЙ") == false)
    }

    /// **Английская строка называет язык самих инструкций, и это не украшение.**
    /// Промпт русский, и модель считает его образцом; строка, которая делает вид,
    /// что окружающего текста нет, оставляет модель взвешивать одну фразу против
    /// тысячи двухсот слов.
    @Test("Английская строка признаёт, что инструкции по-русски")
    func theEnglishLineNamesTheTrap() {
        let line = PromptFragment.answerLanguage(.english)
        #expect(line.contains("инструкции написаны по-русски"))
    }

    /// Позиция замерена отдельно: язык предпоследним держит английский 5 из 5,
    /// так что закрывающая строка остаётся у контракта про образцы — её место
    /// обосновано прежним замером, где модели копировали образец дословно.
    @Test("Язык стоит перед закрывающим контрактом, а не вместо него")
    func languageComesBeforeTheClosingContract() {
        for system in [BriefPrompt.system(profile: .empty, language: .english),
                       AssistPrompt.system(profile: .empty, language: .english)] {
            let language = system.range(of: "ЯЗЫК ОТВЕТА")
            let contract = system.range(of: "Главное, ещё раз")
            #expect(language != nil && contract != nil)
            #expect(language!.lowerBound < contract!.lowerBound)
            #expect(system.hasSuffix("ни одной их строки в ответе.**"))
        }
    }
}

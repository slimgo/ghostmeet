        )
    }

    @Test("Образец огорожен: сказано, что он чужой, и назван признак копирования")
    func theSampleIsFencedByACheckableSign() {
        let system = BriefPrompt.system(profile: .empty)

        // gemini-2.5-flash дважды из трёх вернул этот образец дословно вместо
        // ответа на вопрос вне стека. Резать пару нельзя — она чинит регистр, —
        // поэтому рядом с ней стоит ограда, и признак копирования проверяемый:
        // наличие слова слабый исполнитель проверяет лучше, чем абстракцию.
        #expect(system.contains("Оба образца — из чужого разговора"))
        #expect(system.contains("а спросят тебя про другое"))
        #expect(system.contains("увидел у себя слова «платёж», «идемпотентный», «списание» — значит, выдал образец вместо ответа"))
        // Ограда стоит вплотную к образцу, а не в середине промпта …
        #expect(
            system.range(of: "Оба образца — из чужого разговора")!.lowerBound
                > system.range(of: "А так — речь, её произносят:")!.lowerBound,
            "ограда работает только рядом с тем, что она огораживает"
        )
        // … и повторена в закрывающей строке — сильнейшей позиции текста.
        #expect(system.hasSuffix("Образцы в этих правилах — чужой текст: ни одной их строки в ответе.**"))
    }

    @Test("Вопрос вне стека разрешён прямо: знание темы — не факт о пользователе")
    func aQuestionOutsideTheUsersStackIsAnsweredAnyway() {
        let system = BriefPrompt.system(profile: .empty)

        // Конфликт правил, а не непослушание: с профилем «backend на Go» модель
        // сочла знание JavaScript фактом о пользователе, которого нет в
        // контексте, и трижды из трёх отказалась отвечать про event loop.
        #expect(system.contains("Знание темы — не факт о пользователе"))
        #expect(system.contains("Вопрос запросто может оказаться не про его стек"))
        #expect(system.contains("Разбирай предмет по существу и не приписывай ему опыта с ним"))
        // Разрешение показано парой, как и регистр, а не описано.
        #expect(system.contains("Не так — отказ, за ним и не нажимали:"))
        #expect(system.contains("А так — ответ по теме, за ним и нажимали:"))
        #expect(system.contains("В питоне это упирается в GIL (джил)"))
        // Противовес — на сильном конце, вместе со старым запретом, а не вместо него.
        #expect(system.contains("Ни одного факта, которого нет в контексте, — ни о пользователе, ни о компаниях, ни о рынке"))
        #expect(system.contains("и ответ по существу, когда тема не из его стека"))
    }

    @Test("Образец отказа написан без обращения на «ты»: местоимение переносится вместе с образцом")
    func theRefusalSampleCarriesNoSecondPerson() {
        let sample = PromptFragment.outOfStack

        // Первая редакция кончалась встречным вопросом «ты спрашиваешь не о моём

import Foundation

/// Сколько стенд ждёт того, что обязано случиться на следующем витке.
///
/// **Это предел, а не измерение, и в том вся суть.** Ожидание в стенде — цикл,
/// выходящий в тот же момент, когда условие стало верным; предел нужен ровно для
/// одного — чтобы зависший поток завалил свой тест, а не повесил весь прогон. На
/// исправном коде длинный предел не стоит ни миллисекунды, а платит по нему
/// единственный случай, и платит один раз.
///
/// Отсюда правило: **занижать его не за что, а занижённый стоит дорого.** Он не
/// делает тесты быстрее — он делает их зависимыми от того, чем ещё занята машина.
///
/// Проверено дважды, и второй раз болезненно. Тесты с двухсекундным пределом
/// валили CI на `main` начиная с 0.2.0 — десятком таймаутов подряд, каждый раз в
/// разных тестах, отчего диагноз звучал как «флак». Он же сорвал публикацию
/// 0.3.1: штатный порядок `--dry-run`, потом `--yes` ставит тесты второго прогона
/// сразу за сборкой Release и образа, весь прогон растянулся с 1.7 до 3.4 секунды,
/// и десять ожиданий не уложились. Те же сюиты в одиночку проходят за 0.117 с.
///
/// **Константа общая именно потому, что расхождение и было причиной.** Четыре
/// стенда держали два разных числа — 8 секунд в `ManualCall`, 2 в трёх
/// остальных, — и никто этого не выбирал: одно из них просто отстало. Числу,
/// живущему в одном месте, разойтись не с чем.
///
/// Провайдерские стенды сюда сознательно не переводились: они ждут заглушку
/// потока, а не путь нажатия со снимком экрана и ожиданием распознавания, и ни
/// разу не падали. Условие было записано прямо здесь — «появится падение, придут
/// и они, но не раньше».
///
/// **Оно наступило на релизном прогоне 0.3.2.** Три сюиты — Claude, Gemini,
/// OpenAI-совместимая — уронили один и тот же тест отмены на второй сборке за
/// цикл, там же, где `--dry-run` ставит тесты сразу за сборкой Release: весь
/// прогон растянулся с 1.8 до 7.0 секунды, а свои две секунды у этих стендов
/// остались с тех пор, когда прогон занимал меньше. Ровно предсказанный случай и
/// ровно то же лечение, так что теперь общая константа и у них.
enum TestWait {

    /// Предел ожидания для стендов уровня движка.
    ///
    /// **Тридцать секунд, и это по-прежнему не измерение.** Восемь не выдержали
    /// на выпуске 0.3.2: при load average 25 — Chrome, Docker, десяток
    /// node-процессов, ни один не наш — полный прогон растянулся с 1.6 до 11.3
    /// секунды и уронил одиннадцать ожиданий, тогда как та же сюита в одиночку
    /// прошла за 0.312 с. Код был исправен целиком; не хватило только права на
    /// процессор.
    ///
    /// Отсюда и число: раз предел ничего не измеряет, выбирать его надо не по
    /// самой быстрой машине, а по самой медленной, какую можно вообразить, —
    /// цену платит только по-настоящему зависший тест, и платит один раз.
    static let budget: Duration = .seconds(30)
}

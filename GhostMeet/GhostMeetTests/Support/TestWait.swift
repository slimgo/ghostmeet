import Foundation

/// Сколько стенд ждёт того, что обязано случиться на следующем витке.
///
/// **Это предел, а не измерение, и в том вся суть.** Ожидание в стенде — цикл,
/// выходящий в тот же момент, когда условие стало верным; предел нужен ровно для
/// одного — чтобы зависший поток завалил свой тест, а не повесил весь прогон. На
/// исправном коде длинный предел не стоит ни миллисекунды, а платит по нему
/// единственный случай, и платит один раз.
///
/// Отсюда правило: **занижать его не за что, а занижённый стоит дорого.** Он не
/// делает тесты быстрее — он делает их зависимыми от того, чем ещё занята машина.
///
/// Проверено дважды, и второй раз болезненно. Тесты с двухсекундным пределом
/// валили CI на `main` начиная с 0.2.0 — десятком таймаутов подряд, каждый раз в
/// разных тестах, отчего диагноз звучал как «флак». Он же сорвал публикацию
/// 0.3.1: штатный порядок `--dry-run`, потом `--yes` ставит тесты второго прогона
/// сразу за сборкой Release и образа, весь прогон растянулся с 1.7 до 3.4 секунды,
/// и десять ожиданий не уложились. Те же сюиты в одиночку проходят за 0.117 с.
///
/// **Константа общая именно потому, что расхождение и было причиной.** Четыре
/// стенда держали два разных числа — 8 секунд в `ManualCall`, 2 в трёх
/// остальных, — и никто этого не выбирал: одно из них просто отстало. Числу,
/// живущему в одном месте, разойтись не с чем.
///
/// Провайдерские стенды сюда сознательно не переведены: они ждут заглушку потока,
/// а не путь нажатия со снимком экрана и ожиданием распознавания, и ни разу не
/// падали. Появится падение — придут и они, но не раньше.
enum TestWait {

    /// Предел ожидания для стендов уровня движка.
    static let budget: Duration = .seconds(8)
}
